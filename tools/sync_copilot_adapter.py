#!/usr/bin/env python3
"""Derive the GitHub Copilot adapter (.github/) from the canonical plugin content.

The canonical sources stay where Claude Code reads them: agents/, commands/, skills/, rules/ and
config/orchestration-policy.yaml. This script renders the thin Copilot files that GitHub Copilot discovers
natively:

    .github/agents/<id>.agent.md        from agents/<id>.md            (10 custom agents)
    .github/skills/<command>/SKILL.md   from commands/<command>.md     (10 slash-command skills)
    .github/skills/<skill>/SKILL.md     from skills/<skill>/SKILL.md   (12 internal knowledge skills)
    .github/skills/<rule>/SKILL.md      from rules/<rule>/SKILL.md     (12 internal standards)

It is a build-time helper only (standard library + PyYAML); it adds no runtime and no second policy.

    python tools/sync_copilot_adapter.py            write/refresh the generated files, hashes and the manifest section
    python tools/sync_copilot_adapter.py --check    exit 1 if any generated file is missing, stale or orphaned
    python tools/sync_copilot_adapter.py --matrix   print the ten-command parity matrix (Markdown)
"""

from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
GH = ROOT / ".github"
PLUGIN_NS = "django-engineering:"
MARKER = "<!-- GENERATED by tools/sync_copilot_adapter.py from {src} (sha256 {sha}). Edit the source, then re-run the tool. -->"

#: Claude Code tool name -> GitHub Copilot tool alias (documented aliases only).
TOOL_MAP = {"Read": "read", "Grep": "search", "Glob": "search", "Write": "edit", "Edit": "edit",
            "Bash": "execute", "Agent": "agent", "Task": "agent"}
#: Frontmatter keys that are Claude Code / pack metadata and are not carried to Copilot.
FM = re.compile(r"\A---\n(.*?)\n---\n(.*)\Z", re.S)

COMMAND_NAMES = ["orchestrate", "django-analyze", "django-design", "django-model", "django-api", "django-security",
                 "django-test", "django-optimize", "django-document", "django-review"]
ORCHESTRATOR = "django-orchestrator"

ROOT_NOTE_T = (
    "> **GitHub Copilot invocation.** `<plugin-root>` below is the directory that contains "
    "`config/orchestration-policy.yaml` (the repository root; `{up}` from this file). "
    "Delegate by calling the named custom agent with the agent tool; skills and rules are loaded by "
    "name from `.github/skills/`. The canonical routing policy is `<plugin-root>/config/orchestration-policy.yaml`."
)

ROOT_NOTE_AGENT = ROOT_NOTE_T.replace("{up}", "../..")
ROOT_NOTE_SKILL = ROOT_NOTE_T.replace("{up}", "../../..")


def read(path: Path) -> str:
    return path.read_bytes().decode("utf-8").replace("\r\n", "\n")


def sha(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def split(path: Path) -> tuple[dict, str]:
    match = FM.match(read(path))
    if not match:
        raise SystemExit(f"{path}: no frontmatter")
    return yaml.safe_load(match.group(1)) or {}, match.group(2)


def as_list(value) -> list[str]:
    if value is None:
        return []
    if isinstance(value, str):
        return [p.strip() for p in value.split(",") if p.strip()]
    return [str(p).strip() for p in value]


def one_line(text: str) -> str:
    return " ".join(str(text).split())


def dump_fm(data: dict) -> str:
    out = []
    for key, value in data.items():
        if isinstance(value, bool):
            out.append(f"{key}: {'true' if value else 'false'}")
        elif isinstance(value, list):
            out.append(f"{key}: [{', '.join(value)}]")
        else:
            out.append(f"{key}: {json.dumps(str(value), ensure_ascii=False)}")
    return "---\n" + "\n".join(out) + "\n---\n"


def adapt_body(body: str, *, depth_to_root: str) -> str:
    """Copilot-specific path and naming adaptations; engineering content is untouched."""
    body = body.replace("${CLAUDE_PLUGIN_ROOT}", "<plugin-root>")
    body = body.replace(PLUGIN_NS, "")
    body = body.replace("$ARGUMENTS", "(the text the user typed after the slash command, plus any attached files)")
    body = body.replace("`subagent_type`\n", "agent name\n")
    return body


def rewrite_links(body: str, canonical_dir: str) -> str:
    """`references/x.md` links in a skill resolve against the canonical skill folder, not .github/skills/."""
    prefix = f"../../../{canonical_dir}/"
    # links from a skill or rule up to shared pack content ("../../references/x.md") re-based from .github/skills/<id>/
    body = re.sub(r"\]\(\.\./\.\./(references|templates|config)/", r"](../../../\1/", body)
    body = re.sub(r"\]\((references/[^)]+)\)", lambda m: f"]({prefix}{m.group(1)})", body)
    # links to a sibling skill's references/ ("../other-skill/references/x.md")
    return re.sub(r"\]\(\.\./([a-z-]+/references/[^)]+)\)", lambda m: f"](../../../{canonical_dir.split('/')[0]}/{m.group(1)})", body)


# --------------------------------------------------------------------------- renderers

def render_agent(agent: str) -> tuple[str, str]:
    src = f"agents/{agent}.md"
    meta, body = split(ROOT / src)
    tools = []
    for tool in as_list(meta["tools"]):
        alias = TOOL_MAP[tool]
        if alias not in tools:
            tools.append(alias)
    fm = {"name": agent, "description": one_line(meta["description"]), "tools": tools}
    if agent == ORCHESTRATOR:
        fm["agents"] = specialists()
        fm["user-invocable"] = True
    else:
        fm["user-invocable"] = False
    fm["disable-model-invocation"] = False
    skills = [s.replace(PLUGIN_NS, "") for s in as_list(meta.get("skills"))]
    body = adapt_body(body, depth_to_root="../..")
    extra = (
        "\n## Skills and rules to load (GitHub Copilot)\n\n"
        "Claude Code preloads these from the `skills:` line of `agents/" + agent + ".md`. In Copilot, load each by name "
        "from `.github/skills/<name>/SKILL.md` before you start, and follow them as mandatory:\n\n"
        + "\n".join(f"- `{s}`" for s in skills) + "\n"
    )
    text = dump_fm(fm) + MARKER.format(src=src, sha=sha(read(ROOT / src))) + "\n\n" + ROOT_NOTE_AGENT + "\n" + body.rstrip("\n") + "\n" + extra
    return f".github/agents/{agent}.agent.md", text


def render_command(command: str) -> tuple[str, str]:
    src = f"commands/{command}.md"
    meta, body = split(ROOT / src)
    fm = {"name": command, "description": one_line(meta["description"])}
    if meta.get("argument-hint"):
        fm["argument-hint"] = meta["argument-hint"]
    fm["user-invocable"] = True
    fm["disable-model-invocation"] = False
    body = adapt_body(body, depth_to_root="../../..")
    text = dump_fm(fm) + MARKER.format(src=src, sha=sha(read(ROOT / src))) + "\n\n" + ROOT_NOTE_SKILL + "\n" + body
    return f".github/skills/{command}/SKILL.md", text


def render_skill(kind: str, name: str) -> tuple[str, str]:
    src = f"{kind}/{name}/SKILL.md"
    meta, body = split(ROOT / src)
    fm = {"name": name, "description": one_line(meta["description"]), "user-invocable": False,
          "disable-model-invocation": False}
    body = rewrite_links(adapt_body(body, depth_to_root="../../.."), f"{kind}/{name}")
    text = dump_fm(fm) + MARKER.format(src=src, sha=sha(read(ROOT / src))) + "\n" + body
    return f".github/skills/{name}/SKILL.md", text


def specialists() -> list[str]:
    pol = yaml.safe_load(read(ROOT / "config" / "orchestration-policy.yaml"))
    return list(pol["specialists"])


def knowledge() -> list[str]:
    return sorted(p.parent.name for p in (ROOT / "skills").glob("*/SKILL.md"))


def rules() -> list[str]:
    return sorted(p.parent.name for p in (ROOT / "rules").glob("*/SKILL.md"))


def agents() -> list[str]:
    return sorted(p.stem for p in (ROOT / "agents").glob("*.md"))


def expected() -> dict[str, tuple[str, str, str]]:
    """generated path -> (text, canonical source, adaptation type)."""
    out: dict[str, tuple[str, str, str]] = {}
    for a in agents():
        path, text = render_agent(a)
        out[path] = (text, f"agents/{a}.md", "agent: frontmatter mapped (tools->aliases, visibility), body derived, skills listed")
    for c in COMMAND_NAMES:
        path, text = render_command(c)
        out[path] = (text, f"commands/{c}.md", "command -> user-invocable skill: frontmatter mapped, body derived")
    for s in knowledge():
        path, text = render_skill("skills", s)
        out[path] = (text, f"skills/{s}/SKILL.md", "knowledge skill: user-invocable false, links re-based to canonical references/")
    for r in rules():
        path, text = render_skill("rules", r)
        out[path] = (text, f"rules/{r}/SKILL.md", "standard as internal skill: user-invocable false")
    return out


def existing_generated() -> set[str]:
    found = {p.relative_to(ROOT).as_posix() for p in (GH / "agents").glob("*.agent.md")}
    found |= {p.relative_to(ROOT).as_posix() for p in (GH / "skills").glob("*/SKILL.md")}
    return found


def manifest_section(exp: dict) -> list[dict]:
    rows = []
    for path, (text, src, kind) in sorted(exp.items()):
        rows.append({"canonical_source": src, "claude_code_destination": src, "copilot_destination": path,
                     "adaptation_type": kind, "source_sha256": sha(read(ROOT / src)),
                     "generated_sha256": sha(text), "sync_status": "in-sync"})
    return rows


#: Canonical files extended by the SDLC documentation framework (adaptation AD-16 in the manifest).
SDLC_EXTENDED = ["rules/django-documentation-standards/SKILL.md", "config/orchestration-policy.yaml"]
#: Shared documentation assets both platforms consume in place. The adapter must never copy or fork them.
SDLC_SHARED = ["config/sdlc-documentation-catalog.json", "references/sdlc-documentation-framework.md",
               "references/sdlc-documentation-registry.md", "references/sdlc-mermaid-diagrams.md",
               "tools/sdlc_registry.py"]
REGISTRY_PATH = "docs/sdlc/registry.json"


def sdlc_extended() -> list[str]:
    return sorted(SDLC_EXTENDED + [f"agents/{a}.md" for a in agents()] + [f"commands/{c}.md" for c in COMMAND_NAMES])


def documentation_problems(exp: dict) -> list[str]:
    """One documentation system for both platforms: same catalog, templates, registry format, rules and policy."""
    problems = []
    catalog = json.loads(read(ROOT / "config" / "sdlc-documentation-catalog.json"))
    policy = yaml.safe_load(read(ROOT / "config" / "orchestration-policy.yaml"))
    for shared in SDLC_SHARED:
        if not (ROOT / shared).is_file():
            problems.append(f"missing shared documentation asset: {shared}")
        if any(Path(p).name == Path(shared).name for p in exp):
            problems.append(f"documentation asset must not be generated for Copilot: {shared}")
    stage_ids = {st["id"] for st in catalog["stages"]}
    for t in catalog["types"]:
        if t["owner"] not in policy["specialists"]:
            problems.append(f"catalog type {t['type']}: owner {t['owner']} is not a specialist in the policy")
        if not (ROOT / "templates" / f"{t['template']}.template.md").is_file():
            problems.append(f"catalog type {t['type']}: template {t['template']} does not exist")
    if {st["id"] for st in policy["documentation"]["stages"]} != stage_ids:
        problems.append("orchestration policy documentation stages differ from the catalog stages")
    if policy["documentation"]["registry"] != REGISTRY_PATH:
        problems.append(f"policy registry path is not {REGISTRY_PATH}")
    for path, (text, src, _k) in exp.items():
        if src.startswith(("agents/", "commands/")):
            canonical = read(ROOT / src)
            for marker in ("DOC-M9", "sdlc-documentation-registry"):
                if (marker in canonical) != (marker in text):
                    problems.append(f"{path}: documentation marker {marker!r} differs from its canonical source")
            if "Documentation context" in canonical and "Documentation context" not in text:
                problems.append(f"{path}: lost the Documentation context section")
        if re.search(r"\]\((\.\./)*(references|templates|config)/", text) and src.startswith(("rules/", "skills/")):
            if re.search(r"\]\(\.\./\.\./(references|templates|config)/", text):
                problems.append(f"{path}: pack-content link not re-based for .github/skills/<id>/")
    return problems


def check() -> list[str]:
    problems = []
    exp = expected()
    problems += documentation_problems(exp)
    for path, (text, _src, _k) in exp.items():
        f = ROOT / path
        if not f.is_file():
            problems.append(f"missing: {path}")
        elif read(f) != text:
            problems.append(f"stale: {path}")
    for orphan in sorted(existing_generated() - set(exp)):
        problems.append(f"orphaned (no canonical source): {orphan}")
    return problems


def write() -> None:
    exp = expected()
    for orphan in existing_generated() - set(exp):
        (ROOT / orphan).unlink()
    for path, (text, _s, _k) in exp.items():
        f = ROOT / path
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_bytes(text.encode("utf-8"))


def matrix() -> str:
    lines = ["| Command | Claude Code | Copilot | Same workflow | Status |", "|---|---|---|---|---|"]
    for c in COMMAND_NAMES:
        cc = f"`/django-engineering:{c}` (commands/{c}.md)"
        cp = f"`/{c}` (.github/skills/{c}/SKILL.md)"
        ok = (ROOT / f".github/skills/{c}/SKILL.md").is_file() and not check()
        lines.append(f"| {c} | {cc} | {cp} | derived from the same source | "
                     f"{'structurally in sync; live invocation unverified' if ok else 'OUT OF SYNC'} |")
    return "\n".join(lines)


SKIP = {".git", ".pytest_cache", "__pycache__", ".venv", "venv"}


def update_manifest() -> None:
    """Refresh hashes and the `copilot_adapter` mapping in CANONICAL-MANIFEST.json. Never rewrites sources."""
    mpath = ROOT / "CANONICAL-MANIFEST.json"
    manifest = json.loads(read(mpath))
    exp = expected()
    skills_changed = [f"skills/{s}/SKILL.md" for s in knowledge()]
    ad = {a["id"]: a for a in manifest["adaptations"]}
    ad["AD-15"] = {"id": "AD-15", "reason": "Knowledge skills carry `user-invocable: false` so Claude Code lists only the ten "
                   "commands; agents still preload them and models can still invoke them.", "files": skills_changed}
    manifest["adaptations"] = list(ad.values())
    ad["AD-16"] = {"id": "AD-16", "reason": "SDLC documentation framework: documentation-first protocol (DOC-M9..M16), registry and "
                   "catalog references, Documentation context sections in agents and commands, documentation policy and stage "
                   "table in the orchestration policy. One shared documentation system for Claude Code and Copilot.",
                   "files": sdlc_extended()}
    manifest["adaptations"] = list(ad.values())
    entries = {e["path"]: e for e in manifest["files"]}
    on_disk = sorted(p.relative_to(ROOT).as_posix() for p in ROOT.rglob("*")
                     if p.is_file() and not (set(p.relative_to(ROOT).parts) & SKIP) and p.name != "CANONICAL-MANIFEST.json")
    new_files = []
    for rel in on_disk:
        digest = sha(read(ROOT / rel))
        entry = entries.get(rel)
        if entry is None:
            entry = {"path": rel, "origin": "copilot-adapter" if rel in exp else "standalone-authored", "sha256": digest}
            if rel in exp:
                entry["derived_from"] = exp[rel][1]
            entries[rel] = entry
        entry["sha256"] = digest
        if entry["origin"] == "canonical" and rel in sdlc_extended():
            entry["adaptations"] = sorted(set(entry.get("adaptations", [])) | {"AD-16"})
            entry["identical"] = False
        if entry["origin"] == "canonical" and rel in skills_changed:
            entry["adaptations"] = sorted(set(entry.get("adaptations", [])) | {"AD-15"})
            entry["identical"] = False
    new_files = [entries[r] for r in on_disk]
    manifest["files"] = new_files
    manifest["copilot_adapter"] = {
        "generator": "tools/sync_copilot_adapter.py",
        "note": "Canonical sources are the Claude Code files; Copilot files are derived and verified by --check. "
                "Intentional platform differences: frontmatter fields, tool aliases, skill-preload list, path tokens, "
                "no hook port (docs/copilot.md).",
        "mappings": manifest_section(exp),
    }
    manifest["sdlc_documentation"] = {
        "note": "One documentation system for both platforms. These shared assets are consumed in place by Claude Code and, through "
                "the derived .github files, by GitHub Copilot; the adapter generates no copy of them (checked by --check).",
        "registry": REGISTRY_PATH,
        "shared_assets": SDLC_SHARED,
        "templates": sorted(p.name for p in (ROOT / "templates").glob("*.template.md")),
        "extended_canonical_files": sdlc_extended(),
    }
    mpath.write_bytes((json.dumps(manifest, indent=2, ensure_ascii=False) + "\n").encode("utf-8"))


def main(argv: list[str]) -> int:
    if "--check" in argv:
        problems = check()
        for p in problems:
            print(p)
        print("Copilot adapter in sync." if not problems else f"{len(problems)} problem(s). Run without --check to refresh.")
        return 1 if problems else 0
    if "--matrix" in argv:
        print(matrix())
        return 0
    write()
    update_manifest()
    print(f"Wrote {len(expected())} Copilot adapter files under .github/")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
